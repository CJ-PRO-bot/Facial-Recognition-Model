"""Lightweight, local facial-expression image app for VS Code.

No Gradio / web server needed. Uses Tkinter (built into normal Windows Python),
Pillow, NumPy, Keras 3, and an already installed TensorFlow or PyTorch backend.
OpenCV is optional: without it, upload a tightly cropped face photo.

Run in your *existing* ML/Jupyter Python environment:
    python app_with_feedback.py
"""

from __future__ import annotations
import importlib.util
import json
import os
import random
import sys
from pathlib import Path

# Choose an already installed Keras 3 backend BEFORE importing keras.
if not os.environ.get('KERAS_BACKEND'):
    if importlib.util.find_spec('tensorflow') is not None:
        os.environ['KERAS_BACKEND'] = 'tensorflow'
    elif importlib.util.find_spec('torch') is not None:
        os.environ['KERAS_BACKEND'] = 'torch'
    else:
        sys.exit('Missing TensorFlow/PyTorch backend. Try the Python environment '
                 'you used for model training; see instructions below.')

try:
    import tkinter as tk
    from tkinter import filedialog, messagebox, ttk
    import keras
    import numpy as np
    from PIL import Image, ImageDraw, ImageOps, ImageTk
except (ImportError, ModuleNotFoundError) as err:
    sys.exit(f'Missing library: {err}. Open the environment used for your ML notebook.')

try:
    import cv2  # Optional; this is NOT needed for cropped face images.
except ImportError:
    cv2 = None

HERE = Path(__file__).resolve().parent
CLASS_NAMES = ['Angry', 'Happy', 'Sad']  # Exact original output order
SIZE = (96, 96)
THRESHOLD = 0.55  # Same threshold as the comparison notebook.

# Feedback messages adapted directly from the notebook's RESPONSES dictionary.
# They are rule-based messages, not text generated by the trained CNN.
RESPONSES = {
    'Angry': [
        'You appear to have an angry facial expression. A few slow, deep breaths may help.',
        'Your expression looks tense. A short break or a glass of water might help.',
    ],
    'Happy': [
        'You appear to have a happy facial expression. Great, keep it up!',
        'That looks like a smile. Nice to see it!',
    ],
    'Sad': [
        'You appear to have a sad facial expression. Talking to someone you trust can help.',
        'Your expression looks low. If you often feel this way, consider speaking to a counsellor.',
    ],
    'Uncertain': [
        'Not sure about your expression. Face the camera in good lighting.',
    ],
}
DISCLAIMER = 'This predicts a facial expression only. It cannot tell how you really feel.'


def restore_model():
    config = HERE / 'config.json'
    weights = HERE / 'model.weights.h5'
    if not config.exists() or not weights.exists():
        raise FileNotFoundError('Keep config.json and model.weights.h5 next to app_with_feedback.py')
    # Newer Keras (3.13+) may save optional fields unsupported in Keras 3.10.
    # Remove only the unused null quantization settings; model weights stay intact.
    model_config = json.loads(config.read_text(encoding='utf-8'))

    def remove_unsupported_null_fields(node):
        if isinstance(node, dict):
            if node.get('quantization_config', 'not_present') is None:
                node.pop('quantization_config')
            for value in node.values():
                remove_unsupported_null_fields(value)
        elif isinstance(node, list):
            for value in node:
                remove_unsupported_null_fields(value)

    remove_unsupported_null_fields(model_config)
    model = keras.models.model_from_json(json.dumps(model_config))
    model.load_weights(str(weights))
    if tuple(model.input_shape[1:]) != (96, 96, 3) or model.output_shape[-1] != 3:
        raise ValueError('Unexpected model shape')
    return model


class FaceApp:
    def __init__(self, root: tk.Tk, model):
        self.root = root
        self.model = model
        self.file_path = None
        self.preview_photo = None
        self.root.title('Happy / Angry / Sad — Local CNN Classifier')
        self.root.geometry('700x770')
        self.root.minsize(440, 620)

        top = ttk.Frame(root, padding=18)
        top.pack(fill='both', expand=True)
        ttk.Label(top, text='Facial Expression Classifier',
                  font=('Segoe UI', 18, 'bold')).pack(anchor='w')
        ttk.Label(top, text='Upload a face photo. Everything runs locally on your CPU.',
                  wraplength=570).pack(anchor='w', pady=(3, 14))

        row = ttk.Frame(top)
        row.pack(fill='x')
        ttk.Button(row, text='Choose JPG / PNG', command=self.choose).pack(side='left')
        self.run_btn = ttk.Button(row, text='Predict expression', command=self.predict)
        self.run_btn.pack(side='left', padx=10)

        self.skip = tk.BooleanVar(value=(cv2 is None))
        ttk.Checkbutton(top, text='My image is already cropped to one face (skip detection)',
                        variable=self.skip).pack(anchor='w', pady=(12, 8))
        if cv2 is None:
            ttk.Label(top, text='OpenCV not installed: use tightly cropped face photos.',
                      foreground='#856404').pack(anchor='w')

        self.image_label = ttk.Label(top, text='No image selected', anchor='center')
        self.image_label.pack(fill='both', expand=True, pady=(8, 12))

        self.result = ttk.Label(top, text='Choose a photo to begin.',
                                font=('Segoe UI', 14, 'bold'))
        self.result.pack(anchor='w')
        self.bars = []
        for name in CLASS_NAMES:
            line = ttk.Frame(top)
            line.pack(fill='x', pady=5)
            ttk.Label(line, text=name, width=8).pack(side='left')
            bar = ttk.Progressbar(line, maximum=100, value=0)
            bar.pack(side='left', fill='x', expand=True, padx=8)
            label = ttk.Label(line, text='—', width=7)
            label.pack(side='right')
            self.bars.append((bar, label))
        # An extra UI panel shows feedback from the notebook response templates.
        feedback_frame = ttk.LabelFrame(top, text='Expression-based feedback', padding=12)
        feedback_frame.pack(fill='x', pady=(14, 6))
        self.feedback = ttk.Label(
            feedback_frame,
            text='Upload a photo and click Predict expression to see feedback.',
            wraplength=595, justify='left',
            font=('Segoe UI', 11),
        )
        self.feedback.pack(fill='x')
        self.note = ttk.Label(top, text=DISCLAIMER, wraplength=595, foreground='#575757')
        self.note.pack(anchor='w', pady=(10, 0))

    def choose(self):
        name = filedialog.askopenfilename(
            title='Select a face photo',
            filetypes=[('Images', '*.jpg *.jpeg *.png *.webp *.bmp'), ('All files', '*.*')]
        )
        if not name:
            return
        try:
            with Image.open(name) as img:
                display = ImageOps.exif_transpose(img).convert('RGB')
                display.thumbnail((540, 270))
            self.preview(display)
        except Exception as err:
            messagebox.showerror('Invalid image', str(err))
            return
        self.file_path = name
        self.result.config(text='Ready — click Predict expression', foreground='#242424')
        self.feedback.config(text='Upload a photo and click Predict expression to see feedback.')
        self.note.config(text=DISCLAIMER)
        for bar, label in self.bars:
            bar['value'] = 0
            label.config(text='—')

    def preview(self, image: Image.Image):
        image.thumbnail((540, 270))
        self.preview_photo = ImageTk.PhotoImage(image)
        self.image_label.config(image=self.preview_photo, text='')

    def predict(self):
        if not self.file_path:
            messagebox.showinfo('Choose an image', 'Please choose a JPG or PNG photo first.')
            return
        self.run_btn.config(state='disabled')
        self.root.update_idletasks()
        try:
            with Image.open(self.file_path) as loaded:
                image = ImageOps.exif_transpose(loaded).convert('RGB')
                image.thumbnail((1600, 1600))
            array = np.array(image)
            selected = array
            found_box = None

            if cv2 is not None and not self.skip.get():
                gray = cv2.cvtColor(array, cv2.COLOR_RGB2GRAY)
                xml = cv2.data.haarcascades + 'haarcascade_frontalface_default.xml'
                detector = cv2.CascadeClassifier(xml)
                faces = detector.detectMultiScale(gray, scaleFactor=1.1,
                                                   minNeighbors=5, minSize=(50, 50))
                if len(faces) == 0:
                    self.result.config(text='No face found', foreground='#a16207')
                    self.feedback.config(text='No face detected. Try a clear, front-facing photo, or check the cropped-face box.')
                    self.note.config(text=DISCLAIMER)
                    return
                x, y, w, h = [int(v) for v in max(faces, key=lambda f: f[2] * f[3])]
                found_box = (x, y, w, h)
                pad = int(w * 0.10)
                x1, y1 = max(0, x-pad), max(0, y-pad)
                x2, y2 = min(image.width, x+w+pad), min(image.height, y+h+pad)
                selected = array[y1:y2, x1:x2]

            if cv2 is not None:
                # Same 96x96 INTER_AREA image resize as original inference pipeline.
                small = cv2.resize(selected, SIZE, interpolation=cv2.INTER_AREA)
            else:
                small = np.asarray(Image.fromarray(selected).resize(SIZE, Image.Resampling.BOX))
            # Don't divide by 255: the model already has a Rescaling(1/255) layer.
            batch = small.astype('float32')[None, ...]
            probs = np.asarray(self.model.predict(batch, verbose=0)[0], dtype=float)
            if probs.shape != (3,) or not np.all(np.isfinite(probs)):
                raise ValueError('Unexpected model prediction')
            winner = int(np.argmax(probs))
            confidence = float(probs[winner])
            verdict = CLASS_NAMES[winner] if confidence >= THRESHOLD else 'Uncertain'
            self.result.config(
                text=f'{verdict.upper()} — {confidence:.1%} highest model score',
                foreground={'Happy': '#167342', 'Angry': '#ad3030',
                            'Sad': '#2557a7', 'Uncertain': '#a16207'}[verdict],
            )
            # The CNN chooses the label. We show a matching predefined message.
            self.feedback.config(text=random.choice(RESPONSES[verdict]))
            self.note.config(text=DISCLAIMER + ' Model scores are not calibrated probabilities.')
            for index, (bar, label) in enumerate(self.bars):
                bar['value'] = max(0, min(100, float(probs[index]) * 100))
                label.config(text=f'{probs[index]:.1%}')
            if found_box is not None:
                # Draw face box on the original photo.
                x, y, w, h = found_box
                marked = image.copy()
                draw = ImageDraw.Draw(marked)
                draw.rectangle((x, y, x+w, y+h), outline='#35a853', width=4)
                self.preview(marked)
        except Exception as err:
            self.feedback.config(text='Could not classify this photo. Please try another one.')
            messagebox.showerror('Prediction error', f'{type(err).__name__}: {err}')
        finally:
            self.run_btn.config(state='normal')


def main():
    print(f'Loading your trained CNN with Keras {keras.__version__} '
          f'({keras.backend.backend()} backend)...')
    model = restore_model()
    root = tk.Tk()
    FaceApp(root, model)
    root.mainloop()


if __name__ == '__main__':
    main()
